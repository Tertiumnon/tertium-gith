import { existsSync } from "node:fs";
import path from "node:path";
import { HOOKS_PATH_COMMAND, LOCKFILES, RUN_PREFIX } from "./setup.constants";
import type { PackageJson, PackageManager } from "./setup.types";

function checkBlock(
  manager: PackageManager,
  script: string,
  label: string,
): string {
  return `echo "▶ ${label}"\n${RUN_PREFIX[manager]} ${script}\n\n`;
}

// TypeScript projects always get lint and typecheck, so a missing script fails the commit
// loudly instead of skipping the check. "test" runs only when the project defines it.
export function buildPreCommitHook(
  pkg: PackageJson,
  manager: PackageManager,
  isTypeScript: boolean,
): string {
  const checks = [
    isTypeScript || pkg.scripts?.lint
      ? checkBlock(manager, "lint", "Lint")
      : "",
    isTypeScript || pkg.scripts?.typecheck
      ? checkBlock(manager, "typecheck", "Typecheck")
      : "",
    pkg.scripts?.test ? checkBlock(manager, "test", "Test") : "",
  ].join("");

  return `#!/usr/bin/env sh
# Generated by gith setup -n npm - runs on every commit via core.hooksPath
set -e

${checks}`;
}

export function detectPackageManager(projectPath: string): PackageManager {
  const lockfile = LOCKFILES.find(([file]) =>
    existsSync(path.join(projectPath, file)),
  );
  return lockfile?.[1] ?? "npm";
}

export function isTypeScriptProject(
  projectPath: string,
  pkg: PackageJson,
): boolean {
  if (existsSync(path.join(projectPath, "tsconfig.json"))) return true;
  return Boolean(
    pkg.dependencies?.typescript || pkg.devDependencies?.typescript,
  );
}

// The "prepare" script that points git at the shared hooks, so every clone gets them on install.
export function withPrepareScript(pkg: PackageJson): PackageJson {
  return { ...pkg, scripts: { ...pkg.scripts, prepare: HOOKS_PATH_COMMAND } };
}
