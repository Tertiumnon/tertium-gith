import { execFileSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import type { Flags } from "./args";

const HOOKS_DIR = ".githooks";
const HOOKS_PATH_COMMAND = `git config core.hooksPath ${HOOKS_DIR}`;
const HOOK_NAME = "pre-commit";

type PackageManager = "bun" | "pnpm" | "yarn" | "npm";

interface PackageJson {
  scripts?: {
    lint?: string;
    typecheck?: string;
    test?: string;
    prepare?: string;
    [name: string]: string | undefined;
  };
  dependencies?: { typescript?: string; [name: string]: string | undefined };
  devDependencies?: { typescript?: string; [name: string]: string | undefined };
}

const LOCKFILES: Array<[string, PackageManager]> = [
  ["bun.lock", "bun"],
  ["bun.lockb", "bun"],
  ["pnpm-lock.yaml", "pnpm"],
  ["yarn.lock", "yarn"],
  ["package-lock.json", "npm"],
];

const RUN_PREFIX: Record<PackageManager, string> = {
  bun: "bun run",
  pnpm: "pnpm run",
  yarn: "yarn",
  npm: "npm run",
};

function detectPackageManager(projectPath: string): PackageManager {
  const lockfile = LOCKFILES.find(([file]) =>
    existsSync(path.join(projectPath, file)),
  );
  return lockfile?.[1] ?? "npm";
}

function isTypeScriptProject(projectPath: string, pkg: PackageJson): boolean {
  if (existsSync(path.join(projectPath, "tsconfig.json"))) return true;
  return Boolean(
    pkg.dependencies?.typescript || pkg.devDependencies?.typescript,
  );
}

function checkBlock(
  manager: PackageManager,
  script: string,
  label: string,
): string {
  return `echo "▶ ${label}"\n${RUN_PREFIX[manager]} ${script}\n\n`;
}

// TypeScript projects always get lint and typecheck, so a missing script fails the commit
// loudly instead of skipping the check. "test" runs only when the project defines it.
export function buildPreCommitHook(
  pkg: PackageJson,
  manager: PackageManager,
  isTypeScript: boolean,
): string {
  const checks = [
    isTypeScript || pkg.scripts?.lint
      ? checkBlock(manager, "lint", "Lint")
      : "",
    isTypeScript || pkg.scripts?.typecheck
      ? checkBlock(manager, "typecheck", "Typecheck")
      : "",
    pkg.scripts?.test ? checkBlock(manager, "test", "Test") : "",
  ].join("");

  return `#!/usr/bin/env sh
# Generated by gith setup --hooks - runs on every commit via core.hooksPath
set -e

${checks}`;
}

// Writes .githooks/pre-commit, points core.hooksPath at it, and adds a "prepare" script
// so every install sets the path again.
export function setupGitHooks(
  projectPath: string,
  options: { force?: boolean } = {},
): void {
  if (!existsSync(path.join(projectPath, ".git")))
    throw new Error(`Not a git repository (no .git found): ${projectPath}`);

  const pkg: PackageJson = JSON.parse(
    readFileSync(path.join(projectPath, "package.json"), "utf8"),
  );
  const hookPath = path.join(projectPath, HOOKS_DIR, HOOK_NAME);
  if (existsSync(hookPath) && !options.force)
    throw new Error(
      `${hookPath} already exists. Pass --force to overwrite it.`,
    );

  const manager = detectPackageManager(projectPath);
  const isTypeScript = isTypeScriptProject(projectPath, pkg);

  mkdirSync(path.dirname(hookPath), { recursive: true });
  writeFileSync(hookPath, buildPreCommitHook(pkg, manager, isTypeScript));
  try {
    chmodSync(hookPath, 0o755);
  } catch {
    // Windows has no POSIX mode bits; Git for Windows still runs the hook through its shebang.
  }

  execFileSync("git", ["config", "core.hooksPath", HOOKS_DIR], {
    cwd: projectPath,
    stdio: "inherit",
  });

  if (pkg.scripts?.prepare !== HOOKS_PATH_COMMAND) {
    pkg.scripts = { ...pkg.scripts, prepare: HOOKS_PATH_COMMAND };
    writeFileSync(
      path.join(projectPath, "package.json"),
      `${JSON.stringify(pkg, null, 2)}\n`,
    );
    console.log(`✏️  Added "prepare" → "${HOOKS_PATH_COMMAND}" to package.json`);
  }

  console.log(
    `✅ Wrote ${hookPath} and set core.hooksPath (package manager: ${manager}${isTypeScript ? ", TypeScript" : ""})`,
  );
}

// gith setup --hooks [--force]
export function setup(flags: Flags): void {
  const unknown = [...flags.keys()].filter(
    (key) => key !== "hooks" && key !== "force",
  );
  if (!flags.has("hooks") || unknown.length > 0)
    throw new Error("usage: gith setup --hooks [--force]");
  setupGitHooks(process.cwd(), { force: flags.has("force") });
}
